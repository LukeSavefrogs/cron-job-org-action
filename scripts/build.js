/**
 * Bundles the action and its dependencies into `dist/index.js` (run by GitHub without installing anything), and
 * writes the licenses of the bundled packages into `dist/licenses.txt`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { build } from 'esbuild';

const { metafile } = await build({
  entryPoints: ['src/index.js'],
  outfile: 'dist/index.js',
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  metafile: true,
  // The licenses are collected below
  legalComments: 'none',
  banner: {
    js: [
      '// Generated by `npm run build` from `src/`: do not edit. Licenses: `dist/licenses.txt`.',
      // The CommonJS packages (e.g. `yaml`) require Node.js modules, which an ES module bundle has no `require` for
      "import { createRequire as __createRequire } from 'node:module';",
      'const require = __createRequire(import.meta.url);',
    ].join('\n'),
  },
  logLevel: 'warning',
});

// The root folder of every package with files in the bundle (e.g. `node_modules/yaml`)
const packageFolders = new Set(
  Object.keys(metafile.inputs)
    .map((input) => /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input)?.[1])
    .filter(Boolean),
);

const licenses = [...packageFolders]
  .map((folder) => {
    const { name, version, license } = JSON.parse(readFileSync(join(folder, 'package.json'), 'utf8'));
    const file = readdirSync(folder).find((entry) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(entry));
    if (!file) {
      throw new Error(`${name} has no license file: add its license to dist/licenses.txt by hand.`);
    }
    return `${name}@${version} (${license})\n\n${readFileSync(join(folder, file), 'utf8').trim()}\n`;
  })
  .sort();

writeFileSync('dist/licenses.txt', licenses.join(`\n${'-'.repeat(80)}\n\n`));
console.log(`Bundled into dist/index.js, with ${licenses.length} packages: ${[...packageFolders].map((f) => f.split('node_modules/')[1]).sort().join(', ')}.`);
